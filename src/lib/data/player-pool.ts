export function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/['.]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

export function normalizeName(name: string): string {
  return name
    .toLowerCase()
    .replace(/\b(jr|sr|ii|iii|iv)\b\.?/g, "")
    .replace(/[^a-z0-9]+/g, "")
    .trim();
}

export function buildPlayerPool(scoring: ScoringSettings = DEFAULT_SCORING): Player[] {
  const rankCounters: Record<Position, number> = { QB: 0, RB: 0, WR: 0, TE: 0, K: 0, DEF: 0 };
  const sorted = [...PLAYER_SEEDS].sort((a, b) => a[3] - b[3]);
  return sorted.map((seed) => {
    const [name, position, team, adp, byeWeek, age] = seed;
    rankCounters[position] += 1;
    return {
      id: slugify(name),
      name,
      position,
      team,
      adp,
      projectedPoints: projectedPointsForRank(position, rankCounters[position], scoring),
      byeWeek,
      age,
      injuryStatus: "healthy",
      providerIds: {},
    };
  });
}

export function findPlayerByName(pool: Player[], name: string): Player | null {
  const target = normalizeName(name);
  return pool.find((player) => normalizeName(player.name) === target) ?? null;
}

export function poolIndex(pool: Player[]): Map<string, Player> {
  const index = new Map<string, Player>();
  for (const player of pool) {
    index.set(normalizeName(player.name), player);
  }
  return index;
}
